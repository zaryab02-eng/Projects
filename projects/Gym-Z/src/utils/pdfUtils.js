// PDF export helpers (jsPDF + autoTable). The libraries are loaded on
// demand so they don't slow down the first page load, and they are
// precached by the service worker so exports also work offline.
// Note: jsPDF's built-in fonts can't draw the ₹ symbol, so "Rs." is used.
import { formatDisplayDate, daysUntil } from "./dateUtils.js";
import { getEffectiveExpiryDate } from "./membershipUtils.js";

const BRAND = [184, 115, 51]; // copper
const DARK = [18, 20, 26];

async function loadPdfLibs() {
  const [{ jsPDF }, autoTableModule] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
  ]);
  return { jsPDF, autoTable: autoTableModule.default };
}

const rs = (amount) => `Rs. ${Number(amount || 0).toLocaleString("en-IN")}`;

const safeDate = (value) => (value ? formatDisplayDate(value) : "-");

function getStatus(member) {
  if (member.blacklisted) return "Blacklisted";
  const days = daysUntil(getEffectiveExpiryDate(member));
  return days < 0 ? "Expired" : "Active";
}

function fileSafe(text) {
  return String(text || "file")
    .replace(/[^a-z0-9]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

function drawHeader(doc, gymName, title) {
  const pageWidth = doc.internal.pageSize.getWidth();
  doc.setFillColor(...DARK);
  doc.rect(0, 0, pageWidth, 26, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(gymName || "Gym-Z", 14, 12);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(...BRAND);
  doc.text(title, 14, 19.5);
  doc.setTextColor(0, 0, 0);
}

function drawFooters(doc) {
  const total = doc.internal.getNumberOfPages();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const generated = new Date().toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });
  for (let i = 1; i <= total; i += 1) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(120, 120, 120);
    doc.text(`Generated by Gym-Z on ${generated}`, 14, pageHeight - 8);
    doc.text(`Page ${i} of ${total}`, pageWidth - 14, pageHeight - 8, {
      align: "right",
    });
  }
}

/** One member's full information + renewal history. */
export async function downloadMemberPdf(member, renewals, gymName) {
  const { jsPDF, autoTable } = await loadPdfLibs();
  const doc = new jsPDF({ unit: "mm", format: "a4" });

  drawHeader(doc, gymName, "Member Report");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text(member.fullName || "Member", 14, 38);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(90, 90, 90);
  doc.text(`Status: ${getStatus(member)}`, 14, 44);
  doc.setTextColor(0, 0, 0);

  const rows = [
    ["Phone", member.phone || "-"],
    ["Alt Phone", member.altPhone || "-"],
    ["Age", member.age ? String(member.age) : "-"],
    ["Gender", member.gender || "-"],
    ["Address", member.address || "-"],
    ["Current Plan", member.planName || "-"],
    ["Plan Fee", rs(member.membershipFee)],
    ["Joined", safeDate(member.joiningDate)],
    ["Expires", safeDate(member.expiryDate)],
    ["Lifetime Paid", rs(member.lifetimeAmountPaid)],
    ["Notes", member.notes || "-"],
  ];

  if (member.scheduledMembership) {
    const s = member.scheduledMembership;
    rows.splice(9, 0, [
      "Next Membership",
      `${s.planName} (${safeDate(s.startDate)} to ${safeDate(s.expiryDate)})`,
    ]);
  }

  autoTable(doc, {
    startY: 49,
    body: rows,
    theme: "grid",
    styles: { fontSize: 10, cellPadding: 2.5 },
    columnStyles: {
      0: { fontStyle: "bold", cellWidth: 42, fillColor: [245, 240, 235] },
    },
  });

  const afterInfoY = doc.lastAutoTable.finalY + 10;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Membership & Renewal History", 14, afterInfoY);

  if (renewals?.length) {
    autoTable(doc, {
      startY: afterInfoY + 3,
      head: [["Type", "Plan", "Start", "Expiry", "Amount"]],
      body: renewals.map((r) => [
        r.type === "new" ? "Joined" : "Renewed",
        r.planName || "-",
        safeDate(r.startDate),
        safeDate(r.expiryDate),
        rs(r.amount),
      ]),
      theme: "striped",
      headStyles: { fillColor: BRAND },
      styles: { fontSize: 9.5, cellPadding: 2.5 },
      columnStyles: { 4: { halign: "right" } },
    });
  } else {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.text("No renewal history yet.", 14, afterInfoY + 8);
  }

  drawFooters(doc);
  doc.save(`${fileSafe(member.fullName)}-gym-z.pdf`);
}

/** A table of many members (pass the list you want exported). */
export async function downloadMembersListPdf(members, gymName, label) {
  const { jsPDF, autoTable } = await loadPdfLibs();
  const doc = new jsPDF({ unit: "mm", format: "a4" });

  drawHeader(doc, gymName, `Member List — ${label || "All Members"}`);

  doc.setFontSize(10);
  doc.setTextColor(90, 90, 90);
  doc.text(`Total members: ${members.length}`, 14, 33);
  doc.setTextColor(0, 0, 0);

  autoTable(doc, {
    startY: 37,
    head: [
      ["#", "Name", "Phone", "Plan", "Joined", "Expires", "Status", "Paid"],
    ],
    body: members.map((m, i) => [
      String(i + 1),
      m.fullName || "-",
      m.phone || "-",
      m.planName || "-",
      safeDate(m.joiningDate),
      safeDate(getEffectiveExpiryDate(m)),
      getStatus(m),
      rs(m.lifetimeAmountPaid),
    ]),
    theme: "striped",
    headStyles: { fillColor: BRAND },
    styles: { fontSize: 8.5, cellPadding: 2 },
    columnStyles: { 0: { cellWidth: 8 }, 7: { halign: "right" } },
    didParseCell: (data) => {
      if (data.section === "body" && data.column.index === 6) {
        const v = data.cell.raw;
        if (v === "Expired" || v === "Blacklisted") {
          data.cell.styles.textColor = [200, 40, 40];
        }
      }
    },
  });

  drawFooters(doc);
  doc.save(`gym-members-${fileSafe(label || "all")}.pdf`);
}
